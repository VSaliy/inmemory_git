package io.github.inmemorygit;

import java.io.ByteArrayOutputStream;
import java.nio.ByteBuffer;
import java.nio.CharBuffer;
import java.nio.charset.CharacterCodingException;
import java.nio.charset.CodingErrorAction;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Collection;
import java.util.Collections;
import java.util.Comparator;
import java.util.List;
import java.util.Map;
import java.util.NavigableMap;
import java.util.Objects;
import java.util.Optional;
import java.util.TreeMap;

/**
 * An in-memory transfer of the plumbing in Git's April 7, 2005 first commit.
 * Objects are immutable; the working directory and sorted index are independent.
 * Instances are intended for use by one thread at a time. No method touches disk.
 */
public final class InMemoryGit {
    private static final Comparator<String> PATH_ORDER =
            (left, right) -> Arrays.compareUnsigned(utf8(left), utf8(right));
    private static final int MAX_PARENTS = 16;

    private final InMemoryObjectStore objects = new InMemoryObjectStore();
    private final NavigableMap<String, WorkingFile> working = new TreeMap<>(PATH_ORDER);
    private final NavigableMap<String, IndexEntry> index = new TreeMap<>(PATH_ORDER);

    /** Regular-file modes, including the Unix file-type bits used in the original trees. */
    public enum FileMode {
        REGULAR_FILE(0100644), EXECUTABLE_FILE(0100755);

        private final int bits;

        FileMode(int bits) { this.bits = bits; }

        public int bits() { return bits; }

        public String octalMode() { return Integer.toOctalString(bits); }

        private static FileMode parse(String text) {
            for (FileMode mode : values()) {
                if (mode.octalMode().equals(text)) return mode;
            }
            throw new IllegalArgumentException("Unsupported file mode: " + text);
        }
    }

    /** Immutable binary file value. Content arrays never escape without copying. */
    public static final class WorkingFile {
        private final FileMode mode;
        private final byte[] content;

        public WorkingFile(FileMode mode, byte[] content) {
            this.mode = Objects.requireNonNull(mode, "mode");
            this.content = Objects.requireNonNull(content, "content").clone();
        }

        public FileMode mode() { return mode; }
        public byte[] content() { return content.clone(); }
        public int size() { return content.length; }

        @Override public boolean equals(Object other) {
            return other instanceof WorkingFile file
                    && mode == file.mode && Arrays.equals(content, file.content);
        }

        @Override public int hashCode() { return 31 * mode.hashCode() + Arrays.hashCode(content); }
    }

    public record IndexEntry(String path, FileMode mode, ObjectId objectId) { }
    public record TreeEntry(String path, FileMode mode, ObjectId objectId) { }

    /**
     * An explicit identity and textual date. Dates are preserved verbatim, allowing
     * the ctime-style dates generated by the original commit-tree implementation.
     */
    public record Signature(String name, String email, String date) {
        public Signature {
            validateField(name, "name");
            validateField(email, "email");
            validateField(date, "date");
            if (email.chars().anyMatch(Character::isWhitespace)) {
                throw new IllegalArgumentException("Email cannot contain whitespace");
            }
        }

        private String line() { return name + " <" + email + "> " + date; }

        private static Signature parse(String line) {
            int open = line.indexOf(" <");
            int close = line.indexOf("> ", open + 2);
            if (open < 1 || close < 0) throw new IllegalArgumentException("Invalid signature");
            return new Signature(line.substring(0, open), line.substring(open + 2, close),
                    line.substring(close + 2));
        }
    }

    /** A snapshot plus ordered history links and its exact message text. */
    public record Commit(ObjectId tree, List<ObjectId> parents, Signature author,
                         Signature committer, String message) {
        public Commit {
            Objects.requireNonNull(tree, "tree");
            parents = List.copyOf(parents);
            Objects.requireNonNull(author, "author");
            Objects.requireNonNull(committer, "committer");
            Objects.requireNonNull(message, "message");
        }
    }

    public enum ChangeType { MODIFIED, MODE_CHANGED, DELETED }

    /** The working value is null for a deletion; the indexed value is always present. */
    public record DiffEntry(String path, ChangeType kind, WorkingFile indexed, WorkingFile working) { }

    public void putText(String path, String text) { putFile(path, utf8(text)); }

    public void putFile(String path, byte[] content) { putFile(path, content, FileMode.REGULAR_FILE); }

    /** Change only the working directory. Call updateCache to stage this value. */
    public void putFile(String path, byte[] content, FileMode mode) {
        validatePath(path);
        WorkingFile file = new WorkingFile(mode, content);
        List<String> paths = new ArrayList<>(working.keySet());
        paths.add(path);
        validateNoFileDirectoryConflicts(paths);
        working.put(path, file);
    }

    /** Delete only from the working directory; staging the missing path records removal. */
    public void removeFile(String path) {
        validatePath(path);
        working.remove(path);
    }

    public Optional<WorkingFile> workingFile(String path) {
        validatePath(path);
        return Optional.ofNullable(working.get(path));
    }

    /** Return an independent, immutable view of the current working values. */
    public Map<String, WorkingFile> workingDirectory() {
        return Collections.unmodifiableMap(new TreeMap<>(working));
    }

    /**
     * Stage named working files as blobs, or remove missing paths from the index.
     * All path/conflict checks finish before changing the index or object store.
     */
    public void updateCache(String... paths) {
        Objects.requireNonNull(paths, "paths");
        NavigableMap<String, IndexEntry> candidate = new TreeMap<>(index);
        for (String path : paths) {
            validatePath(path);
            WorkingFile file = working.get(path);
            if (file == null) candidate.remove(path);
            else candidate.put(path, new IndexEntry(path, file.mode(), null));
        }
        validateNoFileDirectoryConflicts(candidate.keySet());
        for (String path : paths) {
            WorkingFile file = working.get(path);
            if (file != null) {
                ObjectId id = objects.put(ObjectType.BLOB, file.content());
                candidate.put(path, new IndexEntry(path, file.mode(), id));
            }
        }
        index.clear();
        index.putAll(candidate);
    }

    public List<IndexEntry> indexEntries() { return List.copyOf(index.values()); }

    /** Serialize the index as one flat tree; later edits cannot change this snapshot. */
    public ObjectId writeTree() {
        ByteArrayOutputStream payload = new ByteArrayOutputStream();
        for (IndexEntry entry : index.values()) {
            requireObject(entry.objectId(), ObjectType.BLOB);
            payload.writeBytes(utf8(entry.mode().octalMode() + " " + entry.path()));
            payload.write(0);
            payload.writeBytes(entry.objectId().bytes());
        }
        return objects.put(ObjectType.TREE, payload.toByteArray());
    }

    /** Inspect a tree, like the original read-tree. This does not change any mutable state. */
    public List<TreeEntry> readTree(ObjectId tree) {
        byte[] payload = requireObject(tree, ObjectType.TREE).content();
        List<TreeEntry> entries = new ArrayList<>();
        int offset = 0;
        String previous = null;
        while (offset < payload.length) {
            int nul = find(payload, offset, (byte) 0);
            int space = find(payload, offset, (byte) ' ');
            if (nul < 0 || space < offset || space >= nul || payload.length - nul - 1 < 20) {
                throw new IllegalArgumentException("Malformed tree entry");
            }
            FileMode mode = FileMode.parse(decodeUtf8(Arrays.copyOfRange(payload, offset, space)));
            String path = decodeUtf8(Arrays.copyOfRange(payload, space + 1, nul));
            validatePath(path);
            if (previous != null && PATH_ORDER.compare(previous, path) >= 0) {
                throw new IllegalArgumentException("Tree entries must have unique, sorted paths");
            }
            ObjectId blob = ObjectId.fromBytes(Arrays.copyOfRange(payload, nul + 1, nul + 21));
            requireObject(blob, ObjectType.BLOB);
            entries.add(new TreeEntry(path, mode, blob));
            previous = path;
            offset = nul + 21;
        }
        validateNoFileDirectoryConflicts(entries.stream().map(TreeEntry::path).toList());
        return List.copyOf(entries);
    }

    /**
     * Write a commit without changing the index, working directory, or a hidden HEAD.
     * Parents are explicit and ordered; this records merge ancestry but performs no merge.
     */
    public ObjectId commitTree(ObjectId tree, List<ObjectId> parents, Signature author,
                               Signature committer, String message) {
        Commit commit = new Commit(tree, parents, author, committer, message);
        readTree(tree);
        if (commit.parents().size() > MAX_PARENTS) {
            throw new IllegalArgumentException("At most 16 parents are supported");
        }
        for (ObjectId parent : commit.parents()) requireObject(parent, ObjectType.COMMIT);
        StringBuilder payload = new StringBuilder("tree ").append(tree.hex()).append('\n');
        for (ObjectId parent : commit.parents()) payload.append("parent ").append(parent.hex()).append('\n');
        payload.append("author ").append(author.line()).append('\n');
        payload.append("committer ").append(committer.line()).append("\n\n").append(message);
        return objects.put(ObjectType.COMMIT, utf8(payload.toString()));
    }

    /** Decode the stored snapshot and history links without moving any reference. */
    public Commit readCommit(ObjectId id) {
        String payload = decodeUtf8(requireObject(id, ObjectType.COMMIT).content());
        int separator = payload.indexOf("\n\n");
        if (separator < 0) throw new IllegalArgumentException("Missing commit header separator");
        String[] lines = payload.substring(0, separator).split("\n", -1);
        if (lines.length < 3 || !lines[0].startsWith("tree ")) {
            throw new IllegalArgumentException("Missing commit tree");
        }
        ObjectId tree = new ObjectId(lines[0].substring(5));
        readTree(tree);
        List<ObjectId> parents = new ArrayList<>();
        int line = 1;
        while (line < lines.length && lines[line].startsWith("parent ")) {
            ObjectId parent = new ObjectId(lines[line++].substring(7));
            requireObject(parent, ObjectType.COMMIT);
            parents.add(parent);
        }
        if (parents.size() > MAX_PARENTS || lines.length != line + 2
                || !lines[line].startsWith("author ") || !lines[line + 1].startsWith("committer ")) {
            throw new IllegalArgumentException("Invalid commit identity headers");
        }
        Signature author = Signature.parse(lines[line].substring(7));
        Signature committer = Signature.parse(lines[line + 1].substring(10));
        return new Commit(tree, parents, author, committer, payload.substring(separator + 2));
    }

    /** Return decoded bytes and type in memory, replacing cat-file's historical tempfile. */
    public GitObject catFile(ObjectId id) { return objects.get(id); }

    public int objectCount() { return objects.objectCount(); }

    /**
     * Compare tracked index values with working files. Untracked files are omitted,
     * as in the original show-diff. Results contain binary values rather than shelling out.
     */
    public List<DiffEntry> showDiff() {
        List<DiffEntry> result = new ArrayList<>();
        for (IndexEntry entry : index.values()) {
            WorkingFile before = new WorkingFile(entry.mode(),
                    requireObject(entry.objectId(), ObjectType.BLOB).content());
            WorkingFile after = working.get(entry.path());
            ChangeType kind;
            if (after == null) kind = ChangeType.DELETED;
            else if (!Arrays.equals(before.content, after.content)) kind = ChangeType.MODIFIED;
            else if (before.mode() != after.mode()) kind = ChangeType.MODE_CHANGED;
            else continue;
            result.add(new DiffEntry(entry.path(), kind, before, after));
        }
        return List.copyOf(result);
    }

    /**
     * Replace the complete working directory and index with a tree.
     * Existing untracked files are also removed. Objects survive.
     */
    public void unpackTree(ObjectId tree) {
        List<TreeEntry> entries = readTree(tree);
        NavigableMap<String, WorkingFile> restored = new TreeMap<>(PATH_ORDER);
        for (TreeEntry entry : entries) {
            restored.put(entry.path(), new WorkingFile(entry.mode(), catFile(entry.objectId()).content()));
        }
        working.clear();
        working.putAll(restored);
        index.clear();
        for (TreeEntry entry : entries) {
            index.put(entry.path(), new IndexEntry(entry.path(), entry.mode(), entry.objectId()));
        }
    }

    /**
     * Compatibility alias for callers using the previous adaptation name.
     * This delegates to {@link #unpackTree(ObjectId)}.
     */
    public void restoreTree(ObjectId tree) {
        unpackTree(tree);
    }

    private GitObject requireObject(ObjectId id, ObjectType expected) {
        GitObject object = objects.get(Objects.requireNonNull(id, "id"));
        if (object.type() != expected) {
            throw new IllegalArgumentException("Expected " + expected.tag() + " object: " + id.hex());
        }
        return object;
    }

    private static int find(byte[] data, int offset, byte value) {
        for (int i = offset; i < data.length; i++) if (data[i] == value) return i;
        return -1;
    }

    private static void validatePath(String path) {
        Objects.requireNonNull(path, "path");
        utf8(path);
        if (path.isEmpty() || path.indexOf('\\') >= 0 || path.indexOf('\0') >= 0
                || path.indexOf(':') >= 0) {
            throw new IllegalArgumentException("Expected an unambiguous relative path: " + path);
        }
        for (String segment : path.split("/", -1)) {
            if (segment.isEmpty() || segment.startsWith(".")) {
                throw new IllegalArgumentException("Empty and dot-prefixed path segments are unsupported: " + path);
            }
        }
    }

    private static void validateNoFileDirectoryConflicts(Collection<String> paths) {
        var names = new java.util.HashSet<>(paths);
        for (String path : paths) {
            for (int slash = path.indexOf('/'); slash >= 0; slash = path.indexOf('/', slash + 1)) {
                if (names.contains(path.substring(0, slash))) {
                    throw new IllegalArgumentException("File/directory path conflict: " + path);
                }
            }
        }
    }

    private static void validateField(String value, String field) {
        Objects.requireNonNull(value, field);
        utf8(value);
        if (value.isBlank() || !value.equals(value.strip()) || value.indexOf('\0') >= 0
                || value.indexOf('\n') >= 0 || value.indexOf('\r') >= 0
                || value.indexOf('<') >= 0 || value.indexOf('>') >= 0) {
            throw new IllegalArgumentException("Invalid signature " + field);
        }
    }

    private static byte[] utf8(String value) {
        Objects.requireNonNull(value, "text");
        try {
            ByteBuffer encoded = StandardCharsets.UTF_8.newEncoder()
                    .onMalformedInput(CodingErrorAction.REPORT)
                    .onUnmappableCharacter(CodingErrorAction.REPORT).encode(CharBuffer.wrap(value));
            byte[] bytes = new byte[encoded.remaining()];
            encoded.get(bytes);
            return bytes;
        } catch (CharacterCodingException error) {
            throw new IllegalArgumentException("Text contains an invalid Unicode sequence", error);
        }
    }

    private static String decodeUtf8(byte[] bytes) {
        try {
            return StandardCharsets.UTF_8.newDecoder().onMalformedInput(CodingErrorAction.REPORT)
                    .onUnmappableCharacter(CodingErrorAction.REPORT).decode(ByteBuffer.wrap(bytes)).toString();
        } catch (CharacterCodingException error) {
            throw new IllegalArgumentException("Object contains invalid UTF-8", error);
        }
    }
}
